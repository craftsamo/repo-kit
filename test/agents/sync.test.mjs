import assert from "node:assert/strict";
import { execFileSync } from "node:child_process";
import {
  existsSync,
  mkdirSync,
  mkdtempSync,
  readdirSync,
  readFileSync,
  readlinkSync,
  realpathSync,
  rmSync,
  symlinkSync,
  writeFileSync,
} from "node:fs";
import { tmpdir } from "node:os";
import path from "node:path";
import { describe, it } from "node:test";

import { assetPath } from "../../src/package-root.mts";
import { markInstalled, sync } from "../../src/agents/sync.mts";

const kitAgents = readdirSync(assetPath("agents"));
const kitSkills = readdirSync(assetPath("skills"));

function repository(t) {
  const root = realpathSync(mkdtempSync(path.join(tmpdir(), "agents-sync-")));
  t.after(() => rmSync(root, { recursive: true, force: true }));
  execFileSync("git", ["init", "--quiet"], { cwd: root });
  return root;
}

const read = (root, file) => readFileSync(path.join(root, file), "utf8");
const exclude = (root) => read(root, ".git/info/exclude");

describe("markInstalled", () => {
  it("adds the marker as a frontmatter comment", () => {
    assert.match(
      markInstalled("---\nname: x\n---\nbody\n"),
      /^---\n# generated by repo-kit .*\nname: x\n---\nbody\n$/,
    );
    assert.throws(() => markInstalled("body\n"), /no frontmatter/);
  });
});

describe("sync", () => {
  it("installs repo-kit's agents and skills and converts them", (t) => {
    const root = repository(t);
    sync(root);

    for (const file of kitAgents) {
      assert.match(
        read(root, `.opencode/agents/${file}`),
        /generated by repo-kit/,
      );
      const name = file.slice(0, -".md".length);
      assert.ok(existsSync(path.join(root, `.claude/agents/${name}.md`)));
      assert.ok(existsSync(path.join(root, `.codex/agents/${name}.toml`)));
    }
    for (const name of kitSkills) {
      assert.match(
        read(root, `.opencode/skills/${name}/SKILL.md`),
        /generated by repo-kit/,
      );
    }
    assert.equal(
      readlinkSync(path.join(root, ".claude/skills")),
      "../.opencode/skills",
    );
    assert.equal(
      readlinkSync(path.join(root, ".agents/skills")),
      "../.opencode/skills",
    );
  });

  it("keeps the repository's own files of the same name", (t) => {
    const root = repository(t);
    const [agent] = kitAgents;
    const [skill] = kitSkills;
    const own = "---\ndescription: Our own reviewer.\n---\n\nOurs.\n";
    mkdirSync(path.join(root, ".opencode/agents"), { recursive: true });
    writeFileSync(path.join(root, `.opencode/agents/${agent}`), own);
    mkdirSync(path.join(root, `.opencode/skills/${skill}`), {
      recursive: true,
    });
    writeFileSync(
      path.join(root, `.opencode/skills/${skill}/SKILL.md`),
      "ours\n",
    );

    const { log } = sync(root);

    assert.equal(read(root, `.opencode/agents/${agent}`), own);
    assert.equal(read(root, `.opencode/skills/${skill}/SKILL.md`), "ours\n");
    assert.ok(log.includes(`kept your own .opencode/agents/${agent}`));
    assert.ok(log.includes(`kept your own .opencode/skills/${skill}`));
    // The repository's agent is still converted for the other tools.
    assert.match(read(root, `.claude/agents/${agent}`), /Our own reviewer/);
    assert.doesNotMatch(
      exclude(root),
      new RegExp(`/\\.opencode/agents/${agent}$`, "m"),
    );
  });

  it("never replaces a skill directory or link the repository has", (t) => {
    const root = repository(t);
    mkdirSync(path.join(root, ".claude/skills/ours"), { recursive: true });
    writeFileSync(path.join(root, ".claude/skills/ours/SKILL.md"), "ours\n");
    const elsewhere = path.join(root, "shared-skills");
    mkdirSync(path.join(elsewhere, kitSkills[0]), { recursive: true });
    writeFileSync(
      path.join(elsewhere, kitSkills[0], "SKILL.md"),
      markInstalled("---\nname: x\n---\n"),
    );
    mkdirSync(path.join(root, ".opencode/skills"), { recursive: true });
    symlinkSync(
      path.join(elsewhere, kitSkills[0]),
      path.join(root, ".opencode/skills", kitSkills[0]),
    );
    mkdirSync(path.join(root, ".agents"));
    symlinkSync(elsewhere, path.join(root, ".agents/skills"));

    const { log } = sync(root);

    assert.equal(read(root, ".claude/skills/ours/SKILL.md"), "ours\n");
    assert.equal(readlinkSync(path.join(root, ".agents/skills")), elsewhere);
    assert.ok(existsSync(path.join(elsewhere, kitSkills[0], "SKILL.md")));
    assert.ok(log.includes("kept your own .claude/skills"));
    assert.ok(log.includes("kept your own .agents/skills"));
    assert.ok(log.includes(`kept your own .opencode/skills/${kitSkills[0]}`));
    assert.doesNotMatch(exclude(root), /^\/\.claude\/skills$/m);
  });

  it("removes what it installed once repo-kit no longer ships it", (t) => {
    const root = repository(t);
    sync(root);
    const stale = path.join(root, ".opencode/skills/retired");
    mkdirSync(stale);
    writeFileSync(
      path.join(stale, "SKILL.md"),
      markInstalled("---\nname: retired\n---\n"),
    );

    const { log } = sync(root);

    assert.ok(!existsSync(stale));
    assert.ok(log.includes("removed .opencode/skills/retired"));
  });

  it("lists what it generated in the repository's info/exclude", (t) => {
    const root = repository(t);
    writeFileSync(path.join(root, ".git/info/exclude"), "# local\n*.log\n");

    sync(root);
    const first = exclude(root);
    sync(root);

    assert.equal(exclude(root), first, "a second sync changes nothing");
    assert.match(first, /^# local\n\*\.log\n\n# >>> repo-kit agents sync/);
    assert.match(first, /^\/\.claude\/skills$/m);
    assert.match(
      first,
      new RegExp(`^/\\.opencode/agents/${kitAgents[0]}$`, "m"),
    );
    assert.equal(
      execFileSync("git", ["status", "--porcelain", "--untracked-files=all"], {
        cwd: root,
        encoding: "utf8",
      }),
      "",
      "nothing generated shows as untracked",
    );
  });

  it("writes nothing the second time", (t) => {
    const root = repository(t);
    sync(root);
    assert.deepEqual(sync(root).log, []);
  });
});

import assert from "node:assert/strict";
import {
  existsSync,
  mkdirSync,
  mkdtempSync,
  readFileSync,
  rmSync,
  statSync,
  writeFileSync,
} from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { after, before, describe, it } from "node:test";

import { convertAgents } from "../../src/agents/sync.mts";

const AGENT_SOURCE = `---
description: "Read-only fixture agent. Prefer invoking through the task tool."
mode: subagent
model: openai/gpt-fixture
hidden: true
options:
  reasoningEffort: xhigh
permission:
  "*": deny
  glob: allow
  grep: allow
  read: allow
  list: allow
  edit: deny
  bash:
    "*": deny
    "git diff*": allow
---

Fixture body with a quote block:

"""tricky toml"""
`;

// The messages of one conversion of the agents under root.
function runSync(root) {
  const result = { generated: [], log: [] };
  convertAgents(root, result);
  return result.log;
}

describe("convertAgents", () => {
  let root;

  before(() => {
    root = mkdtempSync(join(tmpdir(), "sync-agents-"));
    mkdirSync(join(root, ".opencode/agents"), { recursive: true });
    writeFileSync(join(root, ".opencode/agents/fixture.md"), AGENT_SOURCE);
    runSync(root);
  });

  after(() => {
    rmSync(root, { recursive: true, force: true });
  });

  it("generates one definition per target tool", () => {
    for (const file of [
      ".claude/agents/fixture.md",
      ".codex/agents/fixture.toml",
      ".gemini/agents/fixture.md",
      ".grok/agents/fixture.md",
      ".github/agents/fixture.agent.md",
    ]) {
      assert.ok(existsSync(join(root, file)), `missing ${file}`);
      assert.match(
        readFileSync(join(root, file), "utf8"),
        /generated by repo-kit/,
      );
    }
  });

  it("maps permissions to a Claude tool allowlist without model", () => {
    const claude = readFileSync(
      join(root, ".claude/agents/fixture.md"),
      "utf8",
    );
    assert.match(claude, /^name: fixture$/m);
    assert.match(claude, /^tools: Read, Grep, Glob, Bash$/m);
    assert.doesNotMatch(claude, /gpt-fixture/);
    assert.doesNotMatch(claude, /^model:/m);
  });

  it("emits Codex TOML with sandbox, reasoning effort, and escaped body", () => {
    const codex = readFileSync(
      join(root, ".codex/agents/fixture.toml"),
      "utf8",
    );
    assert.match(codex, /^name = "fixture"$/m);
    assert.match(codex, /^sandbox_mode = "read-only"$/m);
    assert.match(codex, /^model_reasoning_effort = "xhigh"$/m);
    assert.match(codex, /developer_instructions = """\n/);
    // The body's `"""` must be broken so it cannot terminate the TOML string.
    assert.doesNotMatch(codex, /tricky toml"""\n/);
    assert.match(codex, /""\\"tricky toml""\\"/);
  });

  it("maps permissions to Gemini tool names", () => {
    const gemini = readFileSync(
      join(root, ".gemini/agents/fixture.md"),
      "utf8",
    );
    assert.match(gemini, /- read_file/);
    assert.match(gemini, /- search_file_content/);
    assert.match(gemini, /- run_shell_command/);
    assert.doesNotMatch(gemini, /write_file/);
  });

  it("maps permissions to Grok Build tool names without model", () => {
    const grok = readFileSync(join(root, ".grok/agents/fixture.md"), "utf8");
    assert.match(grok, /^name: fixture$/m);
    assert.match(
      grok,
      /^description: Read-only fixture agent\. Prefer invoking through the task tool\.$/m,
    );
    assert.match(
      grok,
      /^tools:\n  - read_file\n  - grep\n  - list_dir\n  - run_terminal_command$/m,
    );
    assert.doesNotMatch(grok, /^model:/m);
  });

  it("maps every enabled capability to the complete Grok Build tool allowlist", () => {
    const allCapabilitiesPath = join(
      root,
      ".opencode/agents/all-capabilities.md",
    );
    writeFileSync(
      allCapabilitiesPath,
      `---
description: "Fixture with every capability enabled."
permission:
  read: allow
  grep: allow
  glob: allow
  list: allow
  edit: allow
  bash: allow
  webfetch: allow
  websearch: allow
---

All capabilities fixture.
`,
    );

    try {
      runSync(root);
      const grok = readFileSync(
        join(root, ".grok/agents/all-capabilities.md"),
        "utf8",
      );
      assert.match(
        grok,
        /^tools:\n  - read_file\n  - grep\n  - list_dir\n  - search_replace\n  - run_terminal_command\n  - web_fetch\n  - web_search$/m,
      );
      assert.equal((grok.match(/^  - list_dir$/gm) ?? []).length, 1);
      assert.doesNotMatch(grok, /^model:/m);
    } finally {
      rmSync(allCapabilitiesPath, { force: true });
      runSync(root);
    }
  });

  it("writes generated files read-only so in-place edits fail", () => {
    const filePath = join(root, ".claude/agents/fixture.md");
    assert.equal(
      statSync(filePath).mode & 0o222,
      0,
      "generated file is writable",
    );
    assert.throws(
      () => writeFileSync(filePath, "sneaky edit\n"),
      /EACCES|EPERM/,
    );
  });

  it("replaces a read-only generated file when the source changes", () => {
    writeFileSync(
      join(root, ".opencode/agents/fixture.md"),
      AGENT_SOURCE.replace("Fixture body", "Updated body"),
    );

    runSync(root);

    const claude = readFileSync(
      join(root, ".claude/agents/fixture.md"),
      "utf8",
    );
    assert.match(claude, /Updated body/);
    assert.equal(
      statSync(join(root, ".claude/agents/fixture.md")).mode & 0o222,
      0,
    );

    // Restore the original source and outputs for the remaining tests.
    writeFileSync(join(root, ".opencode/agents/fixture.md"), AGENT_SOURCE);
    runSync(root);
  });

  it("is idempotent (second run writes nothing)", () => {
    assert.deepEqual(runSync(root), []);
  });

  it("removes stale generated files but preserves hand-written ones", () => {
    const handWritten = join(root, ".claude/agents/local-only.md");
    writeFileSync(handWritten, "---\nname: local-only\n---\nkeep me\n");
    rmSync(join(root, ".opencode/agents/fixture.md"));

    runSync(root);

    assert.ok(!existsSync(join(root, ".claude/agents/fixture.md")));
    assert.ok(!existsSync(join(root, ".codex/agents/fixture.toml")));
    assert.ok(!existsSync(join(root, ".grok/agents/fixture.md")));
    assert.ok(existsSync(handWritten), "hand-written agent was deleted");

    // Restore the fixture for any later assertions.
    writeFileSync(join(root, ".opencode/agents/fixture.md"), AGENT_SOURCE);
    runSync(root);
  });

  it("never overwrites a hand-written file at a generated path", () => {
    const conflictPath = join(root, ".gemini/agents/fixture.md");
    rmSync(conflictPath, { force: true });
    writeFileSync(conflictPath, "hand-written, no marker\n");

    const log = runSync(root);

    assert.equal(
      readFileSync(conflictPath, "utf8"),
      "hand-written, no marker\n",
    );
    assert.ok(log.includes("kept your own .gemini/agents/fixture.md"));
  });

  it("parses quoted scalars with colons, escapes, and comments", () => {
    const edgePath = join(root, ".opencode/agents/edge.md");
    writeFileSync(
      edgePath,
      `---
# a comment line
description: "Edge: says \\"hi\\" — and: more"
mode: subagent
options:
  reasoningEffort: 'high'
permission:
  edit: deny
---

Edge body.
`,
    );

    try {
      runSync(root);
      const claude = readFileSync(join(root, ".claude/agents/edge.md"), "utf8");
      assert.match(claude, /^description: "Edge: says \\"hi\\" — and: more"$/m);
      const codex = readFileSync(join(root, ".codex/agents/edge.toml"), "utf8");
      assert.match(codex, /^model_reasoning_effort = "high"$/m);
    } finally {
      rmSync(edgePath, { force: true });
      runSync(root);
    }
  });

  it("converts native V2 permissions arrays and #variant models", () => {
    const v2Path = join(root, ".opencode/agents/v2.md");
    writeFileSync(
      v2Path,
      `---
description: "V2 fixture."
mode: subagent
model: openai/gpt-fixture#xhigh
permissions:
  - action: "*"
    resource: "*"
    effect: deny
  - action: read
    resource: "*"
    effect: allow
  - action: read
    resource: "*.env"
    effect: deny
  - action: shell
    resource: "*"
    effect: deny
  - action: shell
    resource: git diff *
    effect: allow
---

V2 body.
`,
    );

    try {
      runSync(root);
      const claude = readFileSync(join(root, ".claude/agents/v2.md"), "utf8");
      assert.match(claude, /^tools: Read, Glob, Bash$/m);
      assert.doesNotMatch(claude, /^model:/m);
      const codex = readFileSync(join(root, ".codex/agents/v2.toml"), "utf8");
      assert.match(codex, /^sandbox_mode = "read-only"$/m);
      assert.match(codex, /^model_reasoning_effort = "xhigh"$/m);
      assert.match(
        readFileSync(join(root, ".gemini/agents/v2.md"), "utf8"),
        /- list_directory/,
      );
    } finally {
      rmSync(v2Path, { force: true });
      runSync(root);
    }
  });

  it("treats a trailing blanket deny as disabling the capability (last match wins)", () => {
    const orderPath = join(root, ".opencode/agents/order.md");
    writeFileSync(
      orderPath,
      `---
description: "Order fixture."
permissions:
  - action: edit
    resource: "*"
    effect: allow
  - action: edit
    resource: "*"
    effect: deny
  - action: shell
    resource: "*"
    effect: ask
---

Order body.
`,
    );

    try {
      runSync(root);
      const claude = readFileSync(
        join(root, ".claude/agents/order.md"),
        "utf8",
      );
      assert.doesNotMatch(claude, /Edit/);
      assert.match(claude, /Bash/);
    } finally {
      rmSync(orderPath, { force: true });
      runSync(root);
    }
  });

  it("skips agents with an incomplete permissions entry", () => {
    const badPath = join(root, ".opencode/agents/bad-rule.md");
    writeFileSync(
      badPath,
      `---
description: "Bad rule."
permissions:
  - action: read
    effect: allow
---

Body.
`,
    );

    try {
      const log = runSync(root);
      assert.ok(log.some((line) => line.startsWith("skipped bad-rule.md: ")));
      assert.ok(!existsSync(join(root, ".claude/agents/bad-rule.md")));
    } finally {
      rmSync(badPath, { force: true });
      runSync(root);
    }
  });

  it("skips agents using unsupported YAML syntax instead of misconverting", () => {
    const brokenPath = join(root, ".opencode/agents/broken.md");
    writeFileSync(
      brokenPath,
      `---
description: "Uses a list"
tags:
  - one
  - two
---

Body.
`,
    );

    try {
      const log = runSync(root);
      assert.ok(log.some((line) => line.startsWith("skipped broken.md: ")));
      assert.ok(!existsSync(join(root, ".claude/agents/broken.md")));
    } finally {
      rmSync(brokenPath, { force: true });
      runSync(root);
    }
  });

  it("skips gracefully when .opencode/agents is missing", () => {
    const emptyRoot = mkdtempSync(join(tmpdir(), "sync-agents-empty-"));
    try {
      assert.deepEqual(runSync(emptyRoot), []);
    } finally {
      rmSync(emptyRoot, { recursive: true, force: true });
    }
  });
});
